const BLOCKS: [&str; 11] = [
    RAW, STRUCT, FUNCS, GENERICS, NUMBERS, RUNES, COMMENTS, CONTROL,
    LEVELS, UNICODE, INTERFACES,
];

struct Rng(u64);

impl Rng {
    fn next(&mut self) -> usize {
        self.0 ^= self.0 << 13;
        self.0 ^= self.0 >> 7;
        self.0 ^= self.0 << 17;
        (self.0 >> 8) as usize
    }
}

fn render(block: &str, n: usize, rng: &mut Rng) -> String {
    let word = rng.next() % WORDS.len();
    block
        .replace("@N@", &n.to_string())
        .replace("@W@", WORDS[word])
        .replace("@C@", CAPS[word])
        .replace("@u@", "\\u")
}

fn generate(target: usize) -> String {
    let mut rng = Rng(SEED);
    let mut text = String::from(HEADER);
    let mut lines = text.matches('\n').count();
    let mut n = 1;
    let mut misses = 0;
    while misses < 8 {
        let pick = if n <= BLOCKS.len() {
            n - 1
        } else {
            rng.next() % BLOCKS.len()
        };
        let block = render(BLOCKS[pick], n, &mut rng);
        let added = block.matches('\n').count() + 1;
        if lines + added > target {
            misses += 1;
            n += 1;
            continue;
        }
        text.push('\n');
        text.push_str(&block);
        lines += added;
        n += 1;
    }
    text
}

fn main() -> ExitCode {
    let dir = Path::new(env!("CARGO_MANIFEST_DIR"))
        .join("../../bench/fixtures/go");
    for (tier, target) in TIERS {
        let path = dir.join(format!("{tier}.go.txt"));
        let text = generate(target);
        if let Err(err) = fs::write(&path, &text) {
            eprintln!("cannot write {}: {err}", path.display());
            return ExitCode::FAILURE;
        }
        println!(
            "{} {} lines",
            path.display(),
            text.matches('\n').count()
        );
    }
    ExitCode::SUCCESS
}
