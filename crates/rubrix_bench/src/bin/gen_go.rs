struct Rng(u64);

impl Rng {
    fn next(&mut self) -> usize {
        self.0 ^= self.0 << 13;
        self.0 ^= self.0 >> 7;
        self.0 ^= self.0 << 17;
        (self.0 >> 8) as usize
    }

    fn below(&mut self, n: usize) -> usize {
        self.next() % n
    }

    fn chance(&mut self, percent: usize) -> bool {
        self.below(100) < percent
    }

    fn pick(
        &mut self,
        items: &'static [&'static str],
    ) -> &'static str {
        items[self.below(items.len())]
    }
}

#[derive(Clone, Copy)]
struct Ctx {
    looping: bool,
}

struct Gen {
    rng: Rng,
    out: Vec<String>,
    plain: bool,
}

impl Gen {
    fn line(&mut self, indent: usize, text: &str) {
        if text.is_empty() {
            self.out.push(String::new());
        } else {
            self.out.push(format!("{}{text}", "\t".repeat(indent)));
        }
    }

    fn ident(&mut self) -> String {
        let noun = self.rng.pick(NOUNS);
        match self.rng.below(8) {
            0 => camel(&[self.rng.pick(VERBS), noun]),
            1 => camel(&[self.rng.pick(ADJECTIVES), noun]),
            2 => camel(&[noun, self.rng.pick(NOUNS)]),
            3 => format!("{noun}{}", self.rng.below(10)),
            _ => noun.to_string(),
        }
    }

    fn exported(&mut self) -> String {
        capitalise(&self.ident())
    }

    fn fresh(&mut self, used: &mut Vec<String>) -> String {
        let mut name = self.ident();
        while used.contains(&name) {
            name = format!("{name}{}", self.rng.below(100));
        }
        used.push(name.clone());
        name
    }

    fn sentence(&mut self) -> String {
        let a = self.rng.pick(NOUNS);
        let b = self.rng.pick(NOUNS);
        let adjective = self.rng.pick(ADJECTIVES);
        let verb = self.rng.pick(VERBS);
        let mut text = match self.rng.below(8) {
            0 => format!("{verb} the {adjective} {a} of each {b}"),
            1 => format!("return the {adjective} {a} for a {b}"),
            2 => format!("{a} and {b} share one {adjective} {verb}"),
            3 => format!("skip the {a} when the {b} is {adjective}"),
            4 => format!("{verb} every {a} before the {b} closes"),
            5 => format!(
                "the {adjective} {a} must not outlive its {b}"
            ),
            6 => format!(
                "{verb} {a}, then {} the {b}",
                self.rng.pick(VERBS)
            ),
            _ => format!("keep a {adjective} copy of the {a}"),
        };
        if self.rng.chance(30) {
            let c = self.rng.pick(NOUNS);
            let verb = self.rng.pick(VERBS);
            text.push_str(&format!(" and {verb} the {c} afterwards"));
        }
        text
    }

    fn number(&mut self) -> String {
        match self.rng.below(11) {
            0 | 1 => self.rng.below(10).to_string(),
            2 => self.rng.below(1000).to_string(),
            3 => format!(
                "{}_{:03}",
                self.rng.below(99) + 1,
                self.rng.below(1000)
            ),
            4 => format!("0x{:X}", self.rng.below(65536)),
            5 => format!(
                "{}.{}",
                self.rng.below(100),
                self.rng.below(100)
            ),
            6 => format!(
                "{}e{}",
                self.rng.below(10),
                self.rng.below(8)
            ),
            7 => format!("0b{:b}", self.rng.below(255) + 1),
            8 => format!("0o{:o}", self.rng.below(511) + 1),
            9 => format!(
                "0x{:x}p-{}",
                self.rng.below(15) + 1,
                self.rng.below(9)
            ),
            _ => format!("{}i", self.rng.below(9) + 1),
        }
    }

    fn string(&mut self) -> String {
        let body = if self.rng.chance(50) {
            self.rng.pick(NOUNS).to_string()
        } else {
            let first = self.rng.pick(ADJECTIVES);
            let second = self.rng.pick(NOUNS);
            format!("{first} {second}")
        };
        match self.rng.below(10) {
            0 => format!("`{body}\\d+`"),
            1 => format!("\"{body}\\n\""),
            2 => format!("\"{body}: %s\\t%d\""),
            3 => format!(
                "'{}'",
                ["a", "\\n", "\\'", "\\x41", "世"][self.rng.below(5)]
            ),
            _ => format!("\"{body}\""),
        }
    }

    fn atom(&mut self) -> String {
        match self.rng.below(11) {
            0..=3 => self.ident(),
            4 | 5 => self.number(),
            6 | 7 => self.string(),
            8 => ["true", "false", "nil"][self.rng.below(3)]
                .to_string(),
            9 => format!("{}.{}", self.ident(), self.exported()),
            _ => format!(
                "{}.{}.{}",
                self.ident(),
                self.ident(),
                self.exported()
            ),
        }
    }

    fn ty(&mut self, depth: u32) -> String {
        if depth == 0 {
            return self.rng.pick(BASIC_TYPES).to_string();
        }
        let d = depth - 1;
        match self.rng.below(14) {
            0..=4 => self.rng.pick(BASIC_TYPES).to_string(),
            5 => format!("[]{}", self.ty(d)),
            6 => format!("*{}", self.exported()),
            7 => {
                let key =
                    ["string", "int", "int64"][self.rng.below(3)];
                format!("map[{key}]{}", self.ty(d))
            }
            8 => format!("chan {}", self.ty(d)),
            9 | 10 => self.exported(),
            11 => {
                format!("[{}]{}", self.rng.below(16) + 1, self.ty(d))
            }
            12 => [
                "time.Duration",
                "sync.Mutex",
                "strings.Builder",
                "io.Reader",
            ][self.rng.below(4)]
            .to_string(),
            _ => format!("func({}) {}", self.ty(d), self.ty(d)),
        }
    }

    fn expr(&mut self, depth: u32) -> String {
        let depth = depth.min(2);
        if depth == 0 || self.rng.chance(25) {
            return self.atom();
        }
        let d = depth - 1;
        match self.rng.below(18) {
            0 | 1 => {
                let op = self.rng.pick(ARITHMETIC);
                format!("{} {op} {}", self.expr(d), self.expr(d))
            }
            2 => {
                let op = self.rng.pick(COMPARISONS);
                format!("{} {op} {}", self.expr(d), self.expr(d))
            }
            3 => {
                if self.rng.chance(50) {
                    format!("!{}", self.atom())
                } else {
                    format!("-{}", self.ident())
                }
            }
            4 | 5 => {
                let callee = self.callee();
                format!("{callee}({})", self.args(d))
            }
            6 => {
                let target = self.ident();
                let method = self.exported();
                format!("{target}.{method}({})", self.args(d))
            }
            7 => format!("{}.{}", self.ident(), self.exported()),
            8 => format!("{}[{}]", self.ident(), self.expr(d)),
            9 => format!(
                "{}[{}:{}]",
                self.ident(),
                self.expr(d),
                self.expr(d)
            ),
            10 => format!(
                "{}({})",
                self.rng.pick(BASIC_TYPES),
                self.expr(d)
            ),
            11 => self.builtin(d),
            12 if !self.plain => {
                let ty = self.ty(1);
                format!("[]{ty}{{{}}}", self.items(d, 3))
            }
            13 if !self.plain => {
                let ty = self.exported();
                let count = self.rng.below(3);
                let fields: Vec<String> = (0..count)
                    .map(|_| {
                        format!(
                            "{}: {}",
                            self.exported(),
                            self.expr(d)
                        )
                    })
                    .collect();
                let amp = if self.rng.chance(30) { "&" } else { "" };
                format!("{amp}{ty}{{{}}}", fields.join(", "))
            }
            14 if !self.plain => {
                let param = self.ident();
                let ty = self.ty(0);
                let body = self.expr(d);
                format!("func({param} {ty}) {ty} {{ return {body} }}")
            }
            15 => format!("{}.({})", self.ident(), self.ty(1)),
            16 => format!("({})", self.expr(d)),
            _ => self.atom(),
        }
    }

    fn builtin(&mut self, depth: u32) -> String {
        match self.rng.below(7) {
            0 => format!("len({})", self.expr(depth)),
            1 => format!("cap({})", self.ident()),
            2 => format!(
                "append({}, {})",
                self.ident(),
                self.expr(depth)
            ),
            3 => format!(
                "make([]{}, {})",
                self.ty(0),
                self.expr(depth)
            ),
            4 => format!("new({})", self.exported()),
            5 => format!(
                "min({}, {})",
                self.expr(depth),
                self.number()
            ),
            _ => format!("copy({}, {})", self.ident(), self.ident()),
        }
    }

    fn callee(&mut self) -> String {
        match self.rng.below(5) {
            0 => format!(
                "fmt.{}",
                ["Sprintf", "Errorf", "Println", "Sprint"]
                    [self.rng.below(4)]
            ),
            1 => format!(
                "strings.{}",
                ["ToUpper", "TrimSpace", "Split", "Join"]
                    [self.rng.below(4)]
            ),
            _ => camel(&[self.rng.pick(VERBS), self.rng.pick(NOUNS)]),
        }
    }

    fn args(&mut self, depth: u32) -> String {
        let count = self.rng.below(4);
        let args: Vec<String> =
            (0..count).map(|_| self.expr(depth)).collect();
        args.join(", ")
    }

    fn items(&mut self, depth: u32, max: usize) -> String {
        let count = 1 + self.rng.below(max);
        let items: Vec<String> =
            (0..count).map(|_| self.expr(depth)).collect();
        items.join(", ")
    }

    fn condition(&mut self, depth: u32) -> String {
        self.plain = true;
        let text = self.expr(depth);
        self.plain = false;
        text
    }

    fn params(&mut self) -> String {
        let mut used = Vec::new();
        let count = self.rng.below(4);
        let mut parts: Vec<String> = Vec::new();
        for _ in 0..count {
            let name = self.fresh(&mut used);
            let ty = self.ty(1);
            parts.push(format!("{name} {ty}"));
        }
        if self.rng.chance(10) {
            let name = self.fresh(&mut used);
            let ty = self.ty(0);
            parts.push(format!("{name} ...{ty}"));
        }
        parts.join(", ")
    }

    fn results(&mut self) -> String {
        match self.rng.below(8) {
            0..=2 => String::new(),
            3 | 4 => format!(" {}", self.ty(1)),
            5 => format!(" ({}, error)", self.ty(1)),
            6 => {
                let name = self.ident();
                format!(" ({name} {}, err error)", self.ty(0))
            }
            _ => format!(" ({}, {})", self.ty(0), self.ty(1)),
        }
    }

    fn doc(&mut self, name: &str) {
        if self.rng.chance(60) {
            let text = self.sentence();
            self.line(0, &format!("// {name} {text}."));
            if self.rng.chance(20) {
                let more = self.sentence();
                self.line(0, &format!("// {}.", capitalise(&more)));
            }
        }
    }

    fn function(&mut self, depth: u32) {
        let name = self.rng.below(100);
        let name = if name < 60 {
            capitalise(&camel(&[
                self.rng.pick(VERBS),
                self.rng.pick(NOUNS),
            ]))
        } else {
            self.ident()
        };
        self.doc(&name);
        let generic = if self.rng.chance(12) {
            let constraint = [
                "any",
                "comparable",
                "~int | ~string",
                "fmt.Stringer",
            ][self.rng.below(4)];
            format!("[T {constraint}, U any]")
        } else {
            String::new()
        };
        let receiver = if self.rng.chance(35) && generic.is_empty() {
            let ty = self.exported();
            let star = if self.rng.chance(60) { "*" } else { "" };
            format!("(r {star}{ty}) ")
        } else {
            String::new()
        };
        let params = self.params();
        let results = self.results();
        self.line(
            0,
            &format!(
                "func {receiver}{name}{generic}({params}){results} \
                 {{"
            ),
        );
        self.block(1, depth, Ctx { looping: false });
        self.line(0, "}");
    }

    fn structure(&mut self) {
        let name = self.exported();
        self.doc(&name);
        self.line(0, &format!("type {name} struct {{"));
        let mut used = Vec::new();
        for _ in 0..2 + self.rng.below(6) {
            if self.rng.chance(8) {
                let embedded = self.exported();
                self.line(1, &embedded);
                continue;
            }
            let field = if self.rng.chance(75) {
                capitalise(&self.fresh(&mut used))
            } else {
                self.fresh(&mut used)
            };
            let ty = self.ty(2);
            let tag = match self.rng.below(5) {
                0 | 1 => {
                    let key = self.rng.pick(NOUNS);
                    format!(" `json:\"{key},omitempty\"`")
                }
                2 => {
                    let key = self.rng.pick(NOUNS);
                    format!(
                        " `json:\"{key}\" db:\"{key}\" \
                         validate:\"required\"`"
                    )
                }
                3 => format!(" \"{}\"", self.rng.pick(NOUNS)),
                _ => String::new(),
            };
            self.line(1, &format!("{field} {ty}{tag}"));
            if self.rng.chance(10) {
                let note = self.sentence();
                self.line(1, &format!("// {note}"));
            }
        }
        self.line(0, "}");
    }

    fn interface(&mut self) {
        let name = self.exported();
        self.doc(&name);
        self.line(0, &format!("type {name} interface {{"));
        for _ in 0..1 + self.rng.below(4) {
            let method = self.exported();
            let params = self.params();
            let results = self.results();
            self.line(1, &format!("{method}({params}){results}"));
        }
        if self.rng.chance(20) {
            self.line(1, "fmt.Stringer");
        }
        self.line(0, "}");
    }

    fn declarations(&mut self) {
        let constants = self.rng.chance(50);
        let keyword = if constants { "const" } else { "var" };
        self.line(0, &format!("{keyword} ("));
        let ty = self.ty(0);
        let mut used = Vec::new();
        for i in 0..2 + self.rng.below(5) {
            let name = self.fresh(&mut used);
            let text = match (constants, i) {
                (true, 0) => format!("{name} {ty} = iota"),
                (true, _) if self.rng.chance(50) => name,
                (true, _) => format!("{name} = {}", self.number()),
                (false, _) if self.rng.chance(40) => {
                    format!("{name} {}", self.ty(1))
                }
                (false, _) => format!("{name} = {}", self.expr(1)),
            };
            self.line(1, &text);
        }
        self.line(0, ")");
    }

    fn alias(&mut self) {
        let name = self.exported();
        self.doc(&name);
        let text = match self.rng.below(4) {
            0 => format!("type {name} = {}", self.ty(1)),
            1 => {
                format!("type {name} {}", self.rng.pick(BASIC_TYPES))
            }
            2 => format!(
                "type {name} func({}) {}",
                self.ty(1),
                self.ty(1)
            ),
            _ => format!("type {name}[T any] []T"),
        };
        self.line(0, &text);
    }

    fn block(&mut self, indent: usize, depth: u32, ctx: Ctx) {
        for _ in 0..=self.rng.below(if depth > 1 { 3 } else { 4 }) {
            self.statement(indent, depth, ctx);
        }
    }

    fn trailing(&mut self, text: String) -> String {
        if self.rng.chance(12) {
            let note = self.sentence();
            format!("{text} // {note}")
        } else {
            text
        }
    }

    fn assignment(&mut self, indent: usize, depth: u32) {
        let target = self.ident();
        let value = self.expr(depth);
        let text = match self.rng.below(11) {
            0..=2 => format!("{target} := {value}"),
            3 => format!(
                "{target}, {} := {value}, {}",
                self.ident(),
                self.expr(1)
            ),
            4 => format!("{target} = {value}"),
            5 => format!(
                "{target} {} {value}",
                self.rng.pick(ASSIGNMENTS)
            ),
            6 => {
                format!("{target}{}", ["++", "--"][self.rng.below(2)])
            }
            7 => format!("{target}[{}] = {value}", self.expr(1)),
            8 => format!("{target}.{} = {value}", self.exported()),
            9 => format!(
                "{target}, ok := {}[{}]",
                self.ident(),
                self.expr(1)
            ),
            _ => format!("_ = {value}"),
        };
        let text = self.trailing(text);
        self.line(indent, &text);
    }

    fn statement(&mut self, indent: usize, depth: u32, ctx: Ctx) {
        let compound = depth > 0;
        match self.rng.below(100) {
            0..=24 => self.assignment(indent, depth),
            25..=33 => {
                let callee = self.callee();
                let args = self.args(depth);
                let text = self.trailing(format!("{callee}({args})"));
                self.line(indent, &text);
            }
            34..=38 => {
                let name = self.ident();
                let callee = self.callee();
                self.line(indent, &format!("{name} := {callee}("));
                for _ in 0..2 + self.rng.below(3) {
                    let arg = self.expr(depth);
                    self.line(indent + 1, &format!("{arg},"));
                }
                self.line(indent, ")");
            }
            39..=46 if compound => {
                self.conditional(indent, depth, ctx)
            }
            47..=53 if compound => self.for_loop(indent, depth),
            54..=57 if compound => self.switch(indent, depth, ctx),
            58 if compound => self.select(indent, depth, ctx),
            59..=66 => {
                let text = match self.rng.below(3) {
                    0 => "return".to_string(),
                    1 => format!("return {}", self.expr(depth)),
                    _ => format!("return {}, nil", self.expr(depth)),
                };
                let text = self.trailing(text);
                self.line(indent, &text);
            }
            67..=69 => {
                let keyword =
                    if self.rng.chance(50) { "defer" } else { "go" };
                if compound && self.rng.chance(40) {
                    self.line(
                        indent,
                        &format!("{keyword} func() {{"),
                    );
                    self.block(
                        indent + 1,
                        depth - 1,
                        Ctx { looping: false },
                    );
                    self.line(indent, "}()");
                } else {
                    let callee = self.callee();
                    let args = self.args(1);
                    self.line(
                        indent,
                        &format!("{keyword} {callee}({args})"),
                    );
                }
            }
            70..=72 => {
                let name = self.ident();
                let text = if self.rng.chance(50) {
                    format!("var {name} {}", self.ty(1))
                } else {
                    format!("var {name} = {}", self.expr(depth))
                };
                self.line(indent, &text);
            }
            73..=74 => {
                let name = self.ident();
                let value = self.number();
                self.line(indent, &format!("const {name} = {value}"));
            }
            75..=77 if ctx.looping => {
                let word = if self.rng.chance(50) {
                    "break"
                } else {
                    "continue"
                };
                self.line(indent, word);
            }
            78..=79 if compound => {
                let name = self.ident();
                let param = self.ident();
                let ty = self.ty(0);
                self.line(
                    indent,
                    &format!("{name} := func({param} {ty}) {ty} {{"),
                );
                self.block(
                    indent + 1,
                    depth - 1,
                    Ctx { looping: false },
                );
                self.line(indent, "}");
            }
            80..=89 => {
                let note = self.sentence();
                self.line(indent, &format!("// {note}"));
            }
            _ => self.assignment(indent, depth),
        }
    }

    fn conditional(&mut self, indent: usize, depth: u32, ctx: Ctx) {
        let test = self.condition(2);
        let init = match self.rng.below(5) {
            0 => format!(
                "{} := {}; ",
                self.ident(),
                self.callee_call()
            ),
            1 => format!(
                "v, ok := {}[{}]; ",
                self.ident(),
                self.atom()
            ),
            _ => String::new(),
        };
        self.line(indent, &format!("if {init}{test} {{"));
        self.block(indent + 1, depth - 1, ctx);
        for _ in 0..self.rng.below(3) {
            let test = self.condition(2);
            self.line(indent, &format!("}} else if {test} {{"));
            self.block(indent + 1, depth - 1, ctx);
        }
        if self.rng.chance(45) {
            self.line(indent, "} else {");
            self.block(indent + 1, depth - 1, ctx);
        }
        self.line(indent, "}");
    }

    fn callee_call(&mut self) -> String {
        let callee = self.callee();
        let args = self.args(1);
        format!("{callee}({args})")
    }

    fn for_loop(&mut self, indent: usize, depth: u32) {
        let ctx = Ctx { looping: true };
        let head = match self.rng.below(6) {
            0 => String::new(),
            1 => format!(" {}", self.condition(1)),
            2 => {
                let i = ["i", "j", "n"][self.rng.below(3)];
                let limit = self.condition(1);
                format!(" {i} := 0; {i} < {limit}; {i}++")
            }
            3 => format!(
                " _, {} := range {}",
                self.ident(),
                self.ident()
            ),
            4 => format!(
                " {} := range {}",
                self.ident(),
                self.rng.below(20) + 1
            ),
            _ => format!(
                " {}, {} := range {}",
                self.ident(),
                self.ident(),
                self.ident()
            ),
        };
        self.line(indent, &format!("for{head} {{"));
        self.block(indent + 1, depth - 1, ctx);
        self.line(indent, "}");
    }

    fn switch(&mut self, indent: usize, depth: u32, ctx: Ctx) {
        let typed = self.rng.chance(30);
        if typed {
            let value = self.ident();
            self.line(
                indent,
                &format!("switch v := {value}.(type) {{"),
            );
        } else if self.rng.chance(40) {
            self.line(indent, "switch {");
        } else {
            let tag = self.condition(1);
            self.line(indent, &format!("switch {tag} {{"));
        }
        let cases = 1 + self.rng.below(3);
        for i in 0..cases {
            let label = if typed {
                let first = self.ty(1);
                let second = self.ty(0);
                format!("case {first}, {second}:")
            } else {
                let first = self.condition(1);
                format!("case {first}:")
            };
            self.line(indent, &label);
            self.block(indent + 1, depth - 1, ctx);
            if !typed && i + 1 < cases && self.rng.chance(15) {
                self.line(indent + 1, "fallthrough");
            }
        }
        if self.rng.chance(50) {
            self.line(indent, "default:");
            self.block(indent + 1, depth - 1, ctx);
        }
        self.line(indent, "}");
    }

    fn select(&mut self, indent: usize, depth: u32, ctx: Ctx) {
        self.line(indent, "select {");
        let channel = self.ident();
        let value = self.ident();
        self.line(indent, &format!("case {value} := <-{channel}:"));
        self.block(indent + 1, depth - 1, ctx);
        if self.rng.chance(50) {
            let other = self.ident();
            let sent = self.expr(1);
            self.line(indent, &format!("case {other} <- {sent}:"));
            self.block(indent + 1, depth - 1, ctx);
        }
        self.line(indent, "default:");
        self.block(indent + 1, depth - 1, ctx);
        self.line(indent, "}");
    }

    fn unit(&mut self) -> String {
        self.out.clear();
        let depth = 1 + self.rng.below(3) as u32;
        match self.rng.below(100) {
            0..=64 => self.function(depth),
            65..=77 => self.structure(),
            78..=84 => self.interface(),
            85..=92 => self.declarations(),
            _ => self.alias(),
        }
        let mut text = self.out.join("\n");
        text.push('\n');
        text
    }

    fn render(&mut self, block: &str, n: usize) -> String {
        let noun = self.rng.pick(NOUNS);
        block
            .replace("@N@", &n.to_string())
            .replace("@W@", noun)
            .replace("@C@", &capitalise(noun))
            .replace("@u@", "\\u")
    }
}

fn camel(parts: &[&str]) -> String {
    let mut text = String::new();
    for (i, part) in parts.iter().enumerate() {
        if i == 0 {
            text.push_str(part);
        } else {
            text.push_str(&capitalise(part));
        }
    }
    text
}

fn capitalise(text: &str) -> String {
    let mut chars = text.chars();
    match chars.next() {
        Some(first) => first.to_uppercase().chain(chars).collect(),
        None => String::new(),
    }
}

fn generate(target: usize) -> String {
    let mut code = Gen {
        rng: Rng(SEED),
        out: Vec::new(),
        plain: false,
    };
    let mut text = String::from(HEADER);
    let mut lines = text.matches('\n').count();
    let mut n = 1;
    let mut misses = 0;
    while misses < 8 {
        let block = if n <= BLOCKS.len() {
            code.render(BLOCKS[n - 1], n)
        } else if code.rng.chance(10) {
            let pick = code.rng.below(BLOCKS.len());
            code.render(BLOCKS[pick], n)
        } else {
            code.unit()
        };
        let added = block.matches('\n').count() + 1;
        n += 1;
        if lines + added > target {
            misses += 1;
            continue;
        }
        text.push('\n');
        text.push_str(&block);
        lines += added;
    }
    text
}

fn fixture(tier: &str) -> PathBuf {
    PathBuf::from(env!("CARGO_MANIFEST_DIR"))
        .join("../../bench/fixtures/go")
        .join(format!("{tier}.go.txt"))
}

fn main() -> ExitCode {
    for (tier, target) in TIERS {
        let path = fixture(tier);
        let text = generate(target);
        if let Err(err) = fs::write(&path, &text) {
            eprintln!("cannot write {}: {err}", path.display());
            return ExitCode::FAILURE;
        }
        println!(
            "{} {} lines",
            path.display(),
            text.matches('\n').count()
        );
    }
    ExitCode::SUCCESS
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn committed_fixtures_match_the_generator() {
        for (tier, target) in TIERS {
            let path = fixture(tier);
            let committed =
                fs::read_to_string(&path).unwrap_or_else(|err| {
                    panic!("cannot read {}: {err}", path.display())
                });
            assert!(
                committed == generate(target),
                "{} differs from the generator, run `cargo run -p \
                 rubrix_bench --bin gen_go`",
                path.display()
            );
        }
    }
}
