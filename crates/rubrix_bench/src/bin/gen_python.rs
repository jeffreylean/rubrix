//! Writes `bench/fixtures/python/{tiny,small,large}.py.txt`.
//!
//! Each file is built from snippets written for rubrix, in an order
//! fixed by a seed, so a run always writes the same bytes. Every
//! tier of about 800 lines or more holds each construct that the
//! Python lexer handles.
//!
//! ```text
//! cargo run -p rubrix_bench --bin gen_python
//! ```

use std::fs;
use std::path::Path;
use std::process::ExitCode;

const SEED: u64 = 0x5EED_0001;
const TIERS: [(&str, usize); 3] =
    [("tiny", 50), ("small", 800), ("large", 10_000)];
const WORDS: [&str; 10] = [
    "order", "invoice", "session", "widget", "ticket", "report",
    "cursor", "buffer", "packet", "record",
];
const CAPS: [&str; 10] = [
    "Order", "Invoice", "Session", "Widget", "Ticket", "Report",
    "Cursor", "Buffer", "Packet", "Record",
];

const HEADER: &str = r####""""Generated by rubrix_bench gen_python. Do not edit."""

import asyncio
import functools
from dataclasses import dataclass
"####;

const STRINGS: &str = r####"@W@_@N@ = 'single' + "double" + r'raw\n' + R"RAW\d" + u'text' + U"TEXT"
bytes_@N@ = b'bytes' + B"BYTES" + rb'raw\x00' + Rb"mixed" + bR'swap' + BR"both"
fmt_@N@ = f'format {@W@_@N@}' + F"FORMAT {bytes_@N@}" + rf'{@W@_@N@}\d' + fR"{@W@_@N@}\w" + Fr'{@W@_@N@}'
tmpl_@N@ = t'template {@W@_@N@}' + T"TEMPLATE" + tr'{@W@_@N@}\s' + rT"{@W@_@N@}"
escapes_@N@ = 'it\'s' + "say \"hi\"" + 'tab\there' + '\x41@u@00e9\U0001F600' + '\N{GREEK SMALL LETTER ALPHA}' + '\101\7\0'
"####;

const TRIPLE: &str = r####"def describe_@N@(value):
    """Describe a value.

    The summary spans lines and holds "quotes" and 'quotes'.
    A backslash escape \n and an escaped end \""" stay inside.
    """
    text = '''first line
    second line with @W@ and 'quotes'
    '''
    raw = r"""raw \d+ across
    two lines"""
    return text + raw + str(value)
"####;

const FSTRING: &str = r####"def render_@N@(items, width=12, precision=2):
    name = items[0]["@W@"]
    header = f"{name!r:>{width}} {{literal}} {len(items)}"
    nested = f"{items[0]["@W@"]} and {f'{name}'}"
    spec = f"{items[1]:{width}.{precision}f} {name = }"
    block = f"""total {sum(items)}
    {name:>{width}} {
        items[0]
    } done"""
    return header, nested, spec, block
"####;

const NUMBERS: &str = r####"LIMITS_@N@ = (0, 1_000_000, 0xFF_FF, 0o755, 0b1010_1010, 3.14, .5, 1e10, 2.5E-3, 1_0.0_1)
COMPLEX_@N@ = (2j, 3.5J, 1_0j, 1e3j, .5j)
MASK_@N@ = 0xDEAD_BEEF & ~0b1111 | 1 << @N@ ^ 0o17
"####;

const COMMENTS: &str = r####"# @W@ configuration for block @N@ (a comment with "quotes" and 'quotes')
total_@N@ = 1 + \
    2 + \
    3  # trailing comment
message_@N@ = "line one \
line two"
if total_@N@ and message_@N@ is not None: pass; flag_@N@ = True
assert total_@N@, \
    "total must be set"
"####;

const DECORATED: &str = r####"@dataclass(frozen=True)
class @C@@N@(Base):
    """A @W@ widget."""

    label: str = "@W@"
    size: int = 0x1F + @N@
    ratio: float = 1_000.5e-3

    @property
    def title(self):
        return f"{self.label}-{self.size}"

    @staticmethod
    @functools.lru_cache(maxsize=128)
    def build(cls_name, *args, **kwargs):
        return cls_name(*args, **kwargs)

    @classmethod
    def from_text(cls, text: str) -> "@C@@N@":
        label, _, size = text.partition(":")
        return cls(label=label, size=int(size or 0))

    def __matmul__(self, other):
        return self.size @ other.size
"####;

const ASYNC: &str = r####"async def fetch_@N@(session, url: str, *, retries: int = 3) -> bytes:
    for attempt in range(retries):
        try:
            async with session.get(url) as response:
                return await response.read()
        except (TimeoutError, ConnectionError) as error:
            if attempt == retries - 1:
                raise RuntimeError(f"failed {url}") from error
    return b""
"####;

const COMPREHENSION: &str = r####"def summarize_@N@(rows):
    squares = [x ** 2 for x in range(10) if x % 2 == 0]
    lookup = {row["id"]: row for row in rows if row.get("@W@") is not None}
    pairs = sorted(zip(squares, lookup), key=lambda pair: (-pair[0], pair[1]))
    total = sum(v for v in squares) // max(len(pairs), 1)
    return {"total": total, "pairs": pairs, "ok": True, "none": None}
"####;

const ERRORS: &str = r####"class @C@Error@N@(Exception):
    pass


def check_@N@(value: int, limit: int = MAX_LIMIT) -> int:
    if value < 0 or value > limit:
        raise @C@Error@N@(f"value {value} is outside 0..{limit}")
    elif value == 0:
        return 0
    else:
        while value > limit // 2:
            value -= 1
    return value
"####;

const GLOBALS: &str = r####"MAX_LIMIT_@N@ = 4096
DEFAULTS_@N@ = {"name": "@W@", "retries": 3, "ratio": 0.5, "tags": ["a", "b"], "enabled": False}


def configure_@N@(**overrides):
    global MAX_LIMIT_@N@
    settings = dict(DEFAULTS_@N@, **overrides)
    MAX_LIMIT_@N@ = settings.get("retries", 3) * 1024
    return settings
"####;

const UNICODE: &str = r####"def café_@N@(naïve, 名前="日本語"):
    return f"{naïve} → {名前} 😀"
"####;

const BLOCKS: [&str; 11] = [
    STRINGS,
    TRIPLE,
    FSTRING,
    NUMBERS,
    COMMENTS,
    DECORATED,
    ASYNC,
    COMPREHENSION,
    ERRORS,
    GLOBALS,
    UNICODE,
];

struct Rng(u64);

impl Rng {
    fn next(&mut self) -> usize {
        self.0 ^= self.0 << 13;
        self.0 ^= self.0 >> 7;
        self.0 ^= self.0 << 17;
        (self.0 >> 8) as usize
    }
}

fn render(block: &str, n: usize, rng: &mut Rng) -> String {
    let word = rng.next() % WORDS.len();
    block
        .replace("@N@", &n.to_string())
        .replace("@W@", WORDS[word])
        .replace("@C@", CAPS[word])
        .replace("@u@", "\\u")
}

fn generate(target: usize) -> String {
    let mut rng = Rng(SEED);
    let mut text = String::from(HEADER);
    let mut lines = text.matches('\n').count();
    let mut n = 1;
    let mut misses = 0;
    while misses < 8 {
        let pick = if n <= BLOCKS.len() {
            n - 1
        } else {
            rng.next() % BLOCKS.len()
        };
        let block = render(BLOCKS[pick], n, &mut rng);
        let added = block.matches('\n').count() + 2;
        if lines + added > target {
            misses += 1;
            n += 1;
            continue;
        }
        text.push_str("\n\n");
        text.push_str(&block);
        lines += added;
        n += 1;
    }
    text
}

fn main() -> ExitCode {
    let dir = Path::new(env!("CARGO_MANIFEST_DIR"))
        .join("../../bench/fixtures/python");
    for (tier, target) in TIERS {
        let path = dir.join(format!("{tier}.py.txt"));
        let text = generate(target);
        if let Err(err) = fs::write(&path, &text) {
            eprintln!("cannot write {}: {err}", path.display());
            return ExitCode::FAILURE;
        }
        println!(
            "{} {} lines",
            path.display(),
            text.matches('\n').count()
        );
    }
    ExitCode::SUCCESS
}
