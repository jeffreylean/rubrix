struct Rng(u64);

impl Rng {
    fn next(&mut self) -> u64 {
        self.0 = self.0.wrapping_add(0x9E37_79B9_7F4A_7C15);
        let mut z = self.0;
        z = (z ^ (z >> 30)).wrapping_mul(0xBF58_476D_1CE4_E5B9);
        z = (z ^ (z >> 27)).wrapping_mul(0x94D0_49BB_1331_11EB);
        z ^ (z >> 31)
    }

    fn below(&mut self, n: usize) -> usize {
        (self.next() % n as u64) as usize
    }

    fn range(&mut self, low: usize, high: usize) -> usize {
        low + self.below(high - low + 1)
    }

    fn chance(&mut self, percent: usize) -> bool {
        self.below(100) < percent
    }

    fn pick<'a, T>(&mut self, items: &'a [T]) -> &'a T {
        &items[self.below(items.len())]
    }
}

struct Gen {
    rng: Rng,
    out: String,
    lines: usize,
    tables: HashSet<String>,
    keys: HashSet<String>,
}

impl Gen {
    fn line(&mut self, text: &str) {
        self.out.push_str(text);
        self.out.push('\n');
        self.lines += 1 + text.matches('\n').count();
    }

    fn word(&mut self) -> &'static str {
        self.rng.pick(&WORDS)
    }

    fn ident(&mut self) -> String {
        let sep = if self.rng.chance(70) { '_' } else { '-' };
        let mut name = self.word().to_owned();
        for _ in 0..self.rng.below(3) {
            name.push(sep);
            name.push_str(self.word());
        }
        if self.rng.chance(12) {
            let n = self.rng.below(400);
            write!(name, "{sep}{n}").unwrap();
        }
        name
    }

    fn prose(&mut self, low: usize, high: usize) -> String {
        let count = self.rng.range(low, high);
        let mut text = String::new();
        for n in 0..count {
            if n > 0 {
                text.push(' ');
            }
            let word = self.word();
            if n == 0 {
                text.push_str(&word[..1].to_uppercase());
                text.push_str(&word[1..]);
            } else {
                text.push_str(word);
            }
            if n + 1 < count && self.rng.chance(8) {
                text.push(',');
            }
        }
        text.push('.');
        text
    }

    fn key(&mut self) -> String {
        loop {
            let key = match self.rng.below(100) {
                0..60 => self.ident(),
                60..75 => {
                    let (a, b) = (self.word(), self.word());
                    format!("{a}-{b}")
                }
                75..83 => format!("\"{}\"", self.prose(1, 3)),
                83..86 => {
                    format!("'{}.{}'", self.word(), self.word())
                }
                86..96 => {
                    let (a, b) = (self.ident(), self.word());
                    format!("d_{a}.{b}")
                }
                _ => self.rng.range(100, 99_999).to_string(),
            };
            if self.keys.insert(key.clone()) {
                return key;
            }
        }
    }

    fn basic_string(&mut self) -> String {
        let mut text = String::from("\"");
        let words = self.rng.range(1, 9);
        for n in 0..words {
            if n > 0 {
                text.push(' ');
            }
            text.push_str(self.word());
            if self.rng.chance(7) {
                text.push_str(self.rng.pick(&ESCAPES));
            }
        }
        text.push('"');
        text
    }

    fn date(&mut self) -> String {
        let year = self.rng.range(1970, 2035);
        let month = self.rng.range(1, 12);
        let day = self.rng.range(1, 28);
        let time = {
            let (h, m, s) = (
                self.rng.below(24),
                self.rng.below(60),
                self.rng.below(60),
            );
            let frac = if self.rng.chance(30) {
                format!(".{}", self.rng.range(1, 999_999))
            } else {
                String::new()
            };
            format!("{h:02}:{m:02}:{s:02}{frac}")
        };
        let offset = match self.rng.below(4) {
            0 => "Z".to_owned(),
            1 => "z".to_owned(),
            2 => format!("+{:02}:30", self.rng.below(14)),
            _ => format!("-{:02}:00", self.rng.below(12)),
        };
        let date = format!("{year:04}-{month:02}-{day:02}");
        match self.rng.below(5) {
            0 => date,
            1 => time,
            2 => format!("{date}T{time}"),
            3 => format!("{date} {time}"),
            _ => format!("{date}T{time}{offset}"),
        }
    }

    fn number(&mut self) -> String {
        match self.rng.below(10) {
            0 => format!("{}", self.rng.below(100_000)),
            1 => format!("-{}", self.rng.below(5_000)),
            2 => format!(
                "{}_{:03}_{:03}",
                self.rng.range(1, 999),
                self.rng.below(1000),
                self.rng.below(1000)
            ),
            3 => format!("0x{:X}", self.rng.next() & 0xFFFF_FFFF),
            4 => format!("0o{:o}", self.rng.below(0o7777)),
            5 => format!("0b{:b}", self.rng.below(1 << 12)),
            6 => format!(
                "{}.{}",
                self.rng.below(1000),
                self.rng.below(10_000)
            ),
            7 => format!(
                "{}.{}e{}{}",
                self.rng.below(10),
                self.rng.below(100),
                ["+", "-", ""][self.rng.below(3)],
                self.rng.below(30)
            ),
            8 => ["inf", "-inf", "+inf", "nan", "+nan", "-nan"]
                [self.rng.below(6)]
            .to_owned(),
            _ => format!("+{}", self.rng.below(900)),
        }
    }

    fn scalar(&mut self) -> String {
        match self.rng.below(100) {
            0..40 => self.basic_string(),
            40..48 => {
                let path = *self.rng.pick(&PATHS);
                format!("'{path}{}'", self.word())
            }
            48..72 => self.number(),
            72..80 => {
                if self.rng.chance(50) { "true" } else { "false" }
                    .to_owned()
            }
            _ => self.date(),
        }
    }

    fn array(&mut self, depth: usize) -> String {
        let len = self.rng.below(6);
        let items: Vec<String> =
            (0..len).map(|_| self.value(depth + 1)).collect();
        if items.is_empty() {
            "[]".to_owned()
        } else if self.rng.chance(50) {
            format!("[ {} ]", items.join(", "))
        } else {
            format!("[{}]", items.join(","))
        }
    }

    fn inline_table(&mut self, depth: usize) -> String {
        let mut pairs = Vec::new();
        let mut seen = HashSet::new();
        for _ in 0..self.rng.range(1, 4) {
            let key = if self.rng.chance(15) {
                format!("\"{} {}\"", self.word(), self.word())
            } else {
                self.ident()
            };
            if seen.insert(key.clone()) {
                pairs.push(format!(
                    "{key} = {}",
                    self.value(depth + 1)
                ));
            }
        }
        format!("{{ {} }}", pairs.join(", "))
    }

    fn value(&mut self, depth: usize) -> String {
        if depth < 2 {
            match self.rng.below(100) {
                0..12 => return self.array(depth),
                12..18 => return self.inline_table(depth),
                _ => {}
            }
        }
        self.scalar()
    }

    fn comment(&mut self) -> String {
        match self.rng.below(4) {
            0 => format!("# {}", self.prose(2, 12)),
            1 => format!("# {} = {}", self.ident(), self.scalar()),
            2 => format!("#{}", self.prose(1, 4)),
            _ => format!("## {}", self.prose(1, 6)),
        }
    }

    fn entry(&mut self) {
        if self.rng.chance(12) {
            let comment = self.comment();
            self.line(&comment);
        }
        match self.rng.below(100) {
            0..8 => self.multiline_array(),
            8..14 => self.multiline_string(),
            _ => {
                let key = self.key();
                let value = self.value(0);
                let tail = if self.rng.chance(15) {
                    format!(" # {}", self.prose(1, 6))
                } else {
                    String::new()
                };
                self.line(&format!("{key} = {value}{tail}"));
            }
        }
        if self.rng.chance(6) {
            self.line("");
        }
    }

    fn multiline_array(&mut self) {
        let key = self.key();
        self.line(&format!("{key} = ["));
        for _ in 0..self.rng.range(2, 7) {
            let value = self.value(1);
            let tail = if self.rng.chance(20) {
                format!(" # {}", self.prose(1, 5))
            } else {
                String::new()
            };
            self.line(&format!("  {value},{tail}"));
        }
        self.line("]");
    }

    fn multiline_string(&mut self) {
        let key = self.key();
        let literal = self.rng.chance(35);
        let quote = if literal { "'''" } else { "\"\"\"" };
        let rows = self.rng.range(1, 6);
        let mut body = String::new();
        for row in 0..rows {
            let line = match self.rng.below(10) {
                0 => format!("[{}.{}]", self.word(), self.word()),
                1 => {
                    format!("{} = \"{}\"", self.ident(), self.word())
                }
                2 => format!("# {}", self.prose(2, 6)),
                3 if !literal && row + 1 < rows => {
                    format!("{} \\", self.prose(3, 8))
                }
                _ => self.prose(3, 14),
            };
            body.push_str(&line);
            if row + 1 < rows {
                body.push('\n');
            }
        }
        let start = if self.rng.chance(60) { "\n" } else { "" };
        self.line(&format!("{key} = {quote}{start}{body}{quote}"));
    }

    fn header(&mut self) {
        loop {
            let (array, root) = if self.rng.chance(25) {
                (true, *self.rng.pick(&ARRAY_ROOTS))
            } else {
                (false, *self.rng.pick(&TABLE_ROOTS))
            };
            let mut path = root.to_owned();
            let depth = if array { 0 } else { self.rng.below(4) };
            for _ in 0..depth {
                let segment = if self.rng.chance(10) {
                    format!("\"{}.{}\"", self.word(), self.word())
                } else {
                    self.ident()
                };
                let segment = capitalise(&segment);
                path.push('.');
                path.push_str(&segment);
            }
            if array {
                self.line(&format!("[[{path}]]"));
            } else if self.tables.insert(path.clone()) {
                let gap = if self.rng.chance(10) { " " } else { "" };
                self.line(&format!("[{gap}{path}{gap}]"));
            } else {
                continue;
            }
            self.keys.clear();
            return;
        }
    }

    fn section(&mut self) {
        self.line("");
        if self.rng.chance(15) {
            let banner = self.prose(2, 6);
            self.line(&format!("# {}", "-".repeat(40)));
            self.line(&format!("# {banner}"));
        }
        self.header();
        for _ in 0..self.rng.range(2, 14) {
            self.entry();
        }
    }
}

/// Header segments start with a capital, keys with a lowercase
/// letter, so a key never collides with a sub-table.
fn capitalise(text: &str) -> String {
    let skip = usize::from(text.starts_with('"'));
    let (head, tail) = text.split_at(skip + 1);
    format!("{}{}", &head[..skip], head[skip..].to_uppercase()) + tail
}

fn generate(fixed: &str, target: usize) -> String {
    let mut gen_ = Gen {
        rng: Rng(SEED + target as u64),
        out: String::from(fixed),
        lines: fixed.matches('\n').count(),
        tables: HashSet::new(),
        keys: HashSet::new(),
    };
    while gen_.lines < target {
        gen_.section();
    }
    gen_.out
}

fn fixture_path(tier: &str) -> PathBuf {
    Path::new(env!("CARGO_MANIFEST_DIR"))
        .join("../../bench/fixtures/toml")
        .join(format!("{tier}.toml.txt"))
}

fn main() -> ExitCode {
    for (tier, fixed, target) in TIERS {
        let path = fixture_path(tier);
        let text = generate(fixed, target);
        if let Err(err) = fs::write(&path, &text) {
            eprintln!("cannot write {}: {err}", path.display());
            return ExitCode::FAILURE;
        }
        println!(
            "{} {} lines",
            path.display(),
            text.matches('\n').count()
        );
    }
    ExitCode::SUCCESS
}

