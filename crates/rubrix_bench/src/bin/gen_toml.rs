//! Writes `bench/fixtures/toml/{tiny,small,large}.toml.txt`.
//!
//! The small and large tiers start with a fixed block of snippets
//! written for rubrix that holds each construct and scalar form the
//! TOML lexer handles. A seeded random generator then adds sections
//! until the tier has its line count. A section has a table or
//! array-of-tables header and entries whose keys, values, nesting,
//! and line lengths vary, so the large tier does not repeat a few
//! shapes. The tiny tier is a trimmed fixed block of about 50 lines
//! with nothing added. Each tier is valid TOML 1.0.
//!
//! ```text
//! cargo run -p rubrix_bench --bin gen_toml
//! ```

