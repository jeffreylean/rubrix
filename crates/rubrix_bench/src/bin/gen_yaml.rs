//! Writes `bench/fixtures/yaml/{tiny,small,large}.yaml.txt`.
//!
//! The small and large tiers start with a fixed document of
//! snippets written for rubrix that holds each construct and scalar
//! form the YAML lexer handles. A seeded random generator then adds
//! documents until the tier has its line count. A document nests
//! mappings and sequences to varying depths, and mixes block
//! scalars of every kind, flow collections, quoted strings,
//! anchors, aliases, merge keys, tags, comments, and plain scalars
//! of varying length, so the large tier does not repeat a few
//! shapes. The tiny tier is a trimmed fixed document of about 50
//! lines with nothing added. Each tier is valid YAML.
//!
//! ```text
//! cargo run -p rubrix_bench --bin gen_yaml
//! ```

