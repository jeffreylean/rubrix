struct Rng(u64);

impl Rng {
    fn next(&mut self) -> u64 {
        self.0 = self.0.wrapping_add(0x9E37_79B9_7F4A_7C15);
        let mut z = self.0;
        z = (z ^ (z >> 30)).wrapping_mul(0xBF58_476D_1CE4_E5B9);
        z = (z ^ (z >> 27)).wrapping_mul(0x94D0_49BB_1331_11EB);
        z ^ (z >> 31)
    }

    fn below(&mut self, n: usize) -> usize {
        (self.next() % n as u64) as usize
    }

    fn range(&mut self, low: usize, high: usize) -> usize {
        low + self.below(high - low + 1)
    }

    fn chance(&mut self, percent: usize) -> bool {
        self.below(100) < percent
    }

    fn pick<'a, T>(&mut self, items: &'a [T]) -> &'a T {
        &items[self.below(items.len())]
    }
}

struct Gen {
    rng: Rng,
    out: String,
    lines: usize,
    scalars: Vec<String>,
    maps: Vec<String>,
}

impl Gen {
    fn line(&mut self, text: &str) {
        self.out.push_str(text);
        self.out.push('\n');
        self.lines += 1;
    }

    fn word(&mut self) -> &'static str {
        self.rng.pick(&WORDS)
    }

    fn prose(
        &mut self,
        low: usize,
        high: usize,
        commas: bool,
    ) -> String {
        let count = self.rng.range(low, high);
        let mut text = String::new();
        for n in 0..count {
            if n > 0 {
                text.push(' ');
            }
            text.push_str(self.word());
            if commas && n + 1 < count && self.rng.chance(8) {
                text.push(',');
            }
        }
        text
    }

    fn key(&mut self, used: &mut HashSet<String>) -> String {
        loop {
            let key = match self.rng.below(100) {
                0..45 => {
                    let (a, b) = (self.word(), self.word());
                    format!("{a}_{b}")
                }
                45..60 => {
                    let (a, b) = (self.word(), self.word());
                    format!("{a}-{b}")
                }
                60..72 => self.word().to_owned(),
                72..80 => {
                    let (a, b) = (self.word(), self.word());
                    format!("{a}{}{}", b[..1].to_uppercase(), &b[1..])
                }
                80..86 => self.prose(2, 3, false),
                86..91 => format!("\"{}\"", self.prose(1, 3, false)),
                91..95 => format!("'{}'", self.prose(1, 2, false)),
                _ => self.rng.range(100, 599).to_string(),
            };
            if used.insert(key.clone()) {
                return key;
            }
        }
    }

    fn number(&mut self) -> String {
        match self.rng.below(9) {
            0 => self.rng.below(100_000).to_string(),
            1 => format!("-{}", self.rng.below(5_000)),
            2 => format!(
                "{}.{}",
                self.rng.below(1000),
                self.rng.below(10_000)
            ),
            3 => format!("0x{:X}", self.rng.next() & 0xFFFF),
            4 => format!("0o{:o}", self.rng.below(0o7777)),
            5 => format!(
                "{}e{}{}",
                self.rng.range(1, 9),
                ["+", "-", ""][self.rng.below(3)],
                self.rng.below(30)
            ),
            6 => [
                ".inf", "-.inf", "+.inf", ".Inf", ".INF", ".nan",
                ".NaN", ".NAN",
            ][self.rng.below(8)]
            .to_owned(),
            7 => format!(".{}", self.rng.below(900)),
            _ => format!("+{}", self.rng.below(900)),
        }
    }

    fn double_quoted(&mut self) -> String {
        let mut text = String::from("\"");
        for n in 0..self.rng.range(1, 8) {
            if n > 0 {
                text.push(' ');
            }
            text.push_str(self.word());
            if self.rng.chance(9) {
                text.push_str(self.rng.pick(&ESCAPES));
            }
        }
        text.push('"');
        text
    }

    fn single_quoted(&mut self) -> String {
        let mut text = format!("'{}", self.prose(1, 6, true));
        if self.rng.chance(30) {
            text.push_str("''s");
        }
        text.push('\'');
        text
    }

    /// A scalar for one line. `flow` keeps it free of commas and
    /// brackets.
    fn scalar(&mut self, flow: bool) -> String {
        match self.rng.below(100) {
            0..28 => self.prose(1, 12, !flow),
            28..34 if !flow => {
                self.rng.pick(&SPECIAL_PLAIN).to_string()
            }
            34..48 => self.double_quoted(),
            48..54 => self.single_quoted(),
            54..70 => self.number(),
            70..78 => self.rng.pick(&BOOLS).to_string(),
            78..84 => self.rng.pick(&NULLS).to_string(),
            84..88 => {
                let (tag, value) = match self.rng.below(4) {
                    0 => ("!!str", self.number()),
                    1 => ("!!int", self.rng.below(900).to_string()),
                    2 => ("!!float", "1.5".to_owned()),
                    _ => ("!custom", self.prose(1, 3, false)),
                };
                format!("{tag} {value}")
            }
            88..93 if !self.scalars.is_empty() => {
                let name =
                    self.rng.pick(&self.scalars.clone()).clone();
                format!("*{name}")
            }
            _ => self.prose(1, 4, !flow),
        }
    }

    /// A scalar that can take an anchor, which an alias cannot.
    fn anchored_scalar(&mut self) -> String {
        loop {
            let value = self.scalar(false);
            if !value.starts_with('*') {
                return value;
            }
        }
    }

    fn flow(&mut self, depth: usize) -> String {
        let len = self.rng.below(5);
        let mut items = Vec::new();
        let map = self.rng.chance(40);
        let mut used = HashSet::new();
        for _ in 0..len {
            let value = if depth < 2 && self.rng.chance(15) {
                self.flow(depth + 1)
            } else {
                self.scalar(true)
            };
            if map {
                let key = loop {
                    let key =
                        self.prose(1, 2, false).replace(' ', "_");
                    if used.insert(key.clone()) {
                        break key;
                    }
                };
                items.push(format!("{key}: {value}"));
            } else {
                items.push(value);
            }
        }
        let (open, close) = if map { ('{', '}') } else { ('[', ']') };
        let sep = if self.rng.chance(50) { ", " } else { "," };
        format!("{open}{}{close}", items.join(sep))
    }

    fn comment(&mut self, indent: usize) {
        let text = match self.rng.below(3) {
            0 => format!("# {}", self.prose(2, 12, true)),
            1 => format!("#{}", self.prose(1, 4, false)),
            _ => {
                let (key, value) = (self.word(), self.scalar(false));
                format!("# {key}: {value}")
            }
        };
        self.line(&format!("{}{text}", " ".repeat(indent)));
    }

    fn trailing(&mut self) -> String {
        if self.rng.chance(14) {
            format!(" # {}", self.prose(1, 6, true))
        } else {
            String::new()
        }
    }

    fn anchor_name(&mut self) -> String {
        format!("{}{}", self.word(), self.rng.below(100))
    }

    fn block_body(
        &mut self,
        indent: usize,
        keep: bool,
        extra: usize,
    ) {
        let rows = self.rng.range(1, 6);
        for row in 0..rows {
            if row > 0 && self.rng.chance(10) {
                self.line("");
            }
            let more =
                if row > 0 && self.rng.chance(15) { 2 } else { 0 };
            let spaces = " ".repeat(
                indent + more + if row == 0 { extra } else { 0 },
            );
            let text = match self.rng.below(10) {
                0 => {
                    format!("{}: {}", self.word(), self.scalar(false))
                }
                1 => format!("- {}", self.prose(1, 4, true)),
                2 => format!("# {}", self.prose(2, 6, true)),
                3 | 4 => self.rng.pick(&COMMANDS).to_string(),
                _ => self.prose(3, 16, true),
            };
            self.line(&format!("{spaces}{text}"));
        }
        if keep {
            for _ in 0..self.rng.range(1, 2) {
                self.line("");
            }
        }
    }

    fn block_scalar(&mut self, lead: &str, parent: usize) {
        let folded = self.rng.chance(35);
        let style = if folded { '>' } else { '|' };
        let (chomp, keep) = match self.rng.below(4) {
            0 => ("-", false),
            1 => ("+", true),
            _ => ("", false),
        };
        let explicit = self.rng.chance(12);
        let digit = if explicit { "2" } else { "" };
        let note = if self.rng.chance(12) { " # note" } else { "" };
        self.line(&format!("{lead}{style}{digit}{chomp}{note}"));
        let extra = if explicit { 2 } else { 0 };
        self.block_body(parent + 2, keep, extra);
    }

    fn value(&mut self, lead: String, indent: usize, depth: usize) {
        let nest = depth < MAX_DEPTH;
        match self.rng.below(100) {
            0..40 => {
                let value = self.scalar(false);
                let tail = self.trailing();
                self.line(&format!("{lead}{value}{tail}"));
            }
            40..52 if nest => {
                self.line(lead.trim_end());
                self.mapping(indent + 2, depth + 1, None);
            }
            52..62 if nest => {
                self.line(lead.trim_end());
                let at = if self.rng.chance(30) {
                    indent
                } else {
                    indent + 2
                };
                self.sequence(at, depth + 1);
            }
            62..72 => self.block_scalar(&lead, indent),
            72..80 => {
                let flow = self.flow(0);
                self.line(&format!("{lead}{flow}"));
            }
            80..84 => {
                self.line(&format!("{lead}["));
                for n in 0..self.rng.range(2, 5) {
                    let value = self.scalar(true);
                    let tail = self.trailing();
                    let comma = if n < 4 { "," } else { "" };
                    let pad = " ".repeat(indent + 2);
                    self.line(&format!("{pad}{value}{comma}{tail}"));
                }
                self.line(&format!("{}]", " ".repeat(indent)));
            }
            84..88 => {
                let text = self.prose(4, 12, false);
                let (a, b) = text.split_at(text.len() / 2);
                let pad = " ".repeat(indent + 2);
                self.line(&format!("{lead}\"{a}"));
                self.line(&format!("{pad}{b}\""));
            }
            88..94 if nest => {
                let name = self.anchor_name();
                self.line(&format!("{lead}&{name}"));
                self.mapping(indent + 2, depth + 1, None);
                self.maps.push(name);
            }
            94..97 => {
                let name = self.anchor_name();
                let value = self.anchored_scalar();
                self.line(&format!("{lead}&{name} {value}"));
                self.scalars.push(name);
            }
            _ => self.line(lead.trim_end()),
        }
    }

    /// A mapping whose keys sit at `indent`. The first key follows
    /// `first` when it is given, the dash of a sequence item.
    fn mapping(
        &mut self,
        indent: usize,
        depth: usize,
        first: Option<String>,
    ) {
        let mut used = HashSet::new();
        let mut first = first;
        let entries =
            self.rng.range(1, if depth == 0 { 9 } else { 6 });
        let pad = " ".repeat(indent);
        for n in 0..entries {
            if first.is_none() && self.rng.chance(10) {
                self.comment(indent);
            }
            let start = first.take().unwrap_or_else(|| pad.clone());
            if n > 0
                && self.rng.chance(6)
                && !self.maps.is_empty()
                && used.insert("<<".into())
            {
                let name = self.rng.pick(&self.maps.clone()).clone();
                self.line(&format!("{start}<<: *{name}"));
                continue;
            }
            let key = self.key(&mut used);
            self.value(format!("{start}{key}: "), indent, depth);
        }
    }

    fn sequence(&mut self, indent: usize, depth: usize) {
        let pad = " ".repeat(indent);
        for _ in 0..self.rng.range(1, 6) {
            if self.rng.chance(8) {
                self.comment(indent);
            }
            match self.rng.below(100) {
                0..45 => {
                    let value = self.scalar(false);
                    let tail = self.trailing();
                    self.line(&format!("{pad}- {value}{tail}"));
                }
                45..72 if depth < MAX_DEPTH => {
                    self.mapping(
                        indent + 2,
                        depth + 1,
                        Some(format!("{pad}- ")),
                    );
                }
                72..80 => {
                    self.block_scalar(&format!("{pad}- "), indent)
                }
                80..88 => {
                    let flow = self.flow(0);
                    self.line(&format!("{pad}- {flow}"));
                }
                88..94 if depth < MAX_DEPTH => {
                    self.line(&format!("{pad}-"));
                    self.mapping(indent + 2, depth + 1, None);
                }
                _ => {
                    let name = self.anchor_name();
                    let value = self.anchored_scalar();
                    self.line(&format!("{pad}- &{name} {value}"));
                    self.scalars.push(name);
                }
            }
        }
    }

    fn document(&mut self) {
        self.scalars.clear();
        self.maps.clear();
        let marker = match self.rng.below(10) {
            0 => format!("--- # {}", self.prose(1, 4, false)),
            1 => "--- !!map".to_owned(),
            _ => "---".to_owned(),
        };
        self.line(&marker);
        if self.rng.chance(12) {
            self.comment(0);
        }
        if self.rng.chance(15) {
            self.sequence(0, 0);
        } else {
            self.mapping(0, 0, None);
        }
        if self.rng.chance(20) {
            self.line("...");
        }
    }
}

fn generate(fixed: &str, target: usize) -> String {
    let mut gen_ = Gen {
        rng: Rng(SEED + target as u64),
        out: String::from(fixed),
        lines: fixed.matches('\n').count(),
        scalars: Vec::new(),
        maps: Vec::new(),
    };
    while gen_.lines < target {
        gen_.document();
    }
    gen_.out
}

fn fixture_path(tier: &str) -> PathBuf {
    Path::new(env!("CARGO_MANIFEST_DIR"))
        .join("../../bench/fixtures/yaml")
        .join(format!("{tier}.yaml.txt"))
}

fn main() -> ExitCode {
    for (tier, fixed, target) in TIERS {
        let path = fixture_path(tier);
        let text = generate(fixed, target);
        if let Err(err) = fs::write(&path, &text) {
            eprintln!("cannot write {}: {err}", path.display());
            return ExitCode::FAILURE;
        }
        println!(
            "{} {} lines",
            path.display(),
            text.matches('\n').count()
        );
    }
    ExitCode::SUCCESS
}

